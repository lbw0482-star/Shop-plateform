"""Optional Prisma Client Python adapter.

The classroom application starts with the deterministic in-memory repository
in ``app.db`` so it can be demonstrated without a database server. This
adapter is intentionally small: production wiring can call ``connect`` and
``disconnect`` during FastAPI lifespan and inject the generated client into
service classes without changing the route contract.
"""

from __future__ import annotations

from typing import Any

try:  # Generated by ``prisma generate`` when dependencies are installed.
    from prisma import Prisma
except ImportError:  # pragma: no cover - optional classroom dependency
    Prisma = Any  # type: ignore[misc,assignment]


class PrismaRepository:
    def __init__(self) -> None:
        self.client = Prisma() if Prisma is not Any else None

    async def connect(self) -> None:
        if self.client is not None:
            await self.client.connect()

    async def disconnect(self) -> None:
        if self.client is not None:
            await self.client.disconnect()

